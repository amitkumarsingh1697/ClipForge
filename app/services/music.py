"""Background beat under a clip, ducked under speech.

Tracks come from <DATA_DIR>/music/ (put royalty-free / CC0 / your own .mp3 .wav .m4a files there; for example
from the YouTube Audio Library, Pixabay Music or Free Music Archive with a CC0/CC-BY licence).
When that folder has no tracks, ClipForge synthesises its own simple EDM-style beat (kick, clap, hi-hats,
bass) with numpy. It is generated by this code, so there is no copyright claim on it.

Never use commercial songs: Content ID mutes or blocks the clip, and Instagram/TikTok mute it.
"""
from __future__ import annotations

import hashlib
import logging
import wave
from pathlib import Path

import numpy as np

log = logging.getLogger(__name__)
EXTS = {".mp3", ".wav", ".m4a", ".aac", ".ogg", ".flac"}
BUILTIN_NAME = "_clipforge_beat_v1.wav"


def music_dir(data_dir: Path) -> Path:
    d = data_dir / "music"
    d.mkdir(parents=True, exist_ok=True)
    return d


def user_tracks(data_dir: Path) -> list[Path]:
    return sorted(p for p in music_dir(data_dir).iterdir()
                  if p.suffix.lower() in EXTS and not p.name.startswith("_clipforge_"))


def pick_track(data_dir: Path, seed: str) -> Path:
    """Same clip -> same track (re-renders sound the same); different clips rotate through your tracks."""
    tracks = user_tracks(data_dir)
    if tracks:
        i = int(hashlib.md5(seed.encode()).hexdigest(), 16) % len(tracks)
        return tracks[i]
    return builtin_beat(music_dir(data_dir))


def builtin_beat(folder: Path, bpm: float = 124.0, bars: int = 16, sr: int = 44100) -> Path:
    dst = folder / BUILTIN_NAME
    if dst.exists():
        return dst
    beat = 60.0 / bpm
    n = int(sr * beat * 4 * bars)
    out = np.zeros(n, dtype=np.float64)
    rng = np.random.default_rng(7)

    def put(sig: np.ndarray, at: float, gain: float) -> None:
        i = int(at * sr)
        j = min(n, i + len(sig))
        if i < n:
            out[i:j] += gain * sig[: j - i]

    t_k = np.arange(int(0.35 * sr)) / sr
    kick = np.sin(2 * np.pi * (45 * t_k + (110 / 18) * (1 - np.exp(-18 * t_k)))) * np.exp(-7 * t_k)
    t_c = np.arange(int(0.18 * sr)) / sr
    clap = rng.standard_normal(len(t_c)) * np.exp(-22 * t_c)
    clap = np.convolve(clap, np.ones(3) / 3, mode="same")
    t_h = np.arange(int(0.05 * sr)) / sr
    hat = np.diff(rng.standard_normal(len(t_h) + 1)) * np.exp(-90 * t_h)
    roots = [55.0, 55.0, 43.65, 49.0]  # A1 A1 F1 G1
    t_b = np.arange(int(beat / 2 * sr)) / sr
    for bar in range(bars):
        root = roots[bar % 4]
        for q in range(4):
            t0 = (bar * 4 + q) * beat
            put(kick, t0, 0.9)
            if q in (1, 3):
                put(clap, t0, 0.35)
            put(hat, t0 + beat / 2, 0.18)
            put(hat, t0 + beat / 4 * 3, 0.08)
            bass = np.sin(2 * np.pi * root * t_b) + 0.3 * np.sin(2 * np.pi * root * 2 * t_b)
            bass *= np.minimum(1, t_b * 200) * np.exp(-5 * t_b)
            put(bass, t0 + beat / 2, 0.35)
    out /= max(1e-9, np.abs(out).max()) / 0.8
    pcm = (out * 32767).astype("<i2")
    with wave.open(str(dst), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm.tobytes())
    log.info("generated built-in beat %s", dst)
    return dst
